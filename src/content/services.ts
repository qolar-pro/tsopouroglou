/**
 * Build-time integrity check. A typo in a `related` slug would otherwise ship
 * as a dead internal link that nothing catches until someone clicks it.
 * This runs when the module is first imported, which during `next build` is
 * while prerendering — so a bad slug fails the build.
 */
{
  const known = new Set(services.map((s) => s.slug));
  for (const s of services) {
    for (const r of s.related) {
      if (!known.has(r)) {
        throw new Error(
          `services.ts: "${s.slug}" lists related slug "${r}", which does not exist.`
        );
      }
      if (r === s.slug) {
        throw new Error(`services.ts: "${s.slug}" lists itself as related.`);
      }
    }
  }
}
